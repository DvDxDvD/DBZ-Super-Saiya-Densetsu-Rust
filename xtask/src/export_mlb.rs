//! `export-mlb`: Mesen2 labels (`dbz.mlb`) and the tracer's symbols (`symbols.lua`) from
//! `re/symbols.toml`. Both are derived from the game's addresses, so they go to `.work/` only.

use anyhow::Context;
use ssd_oracle::Symbols;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Offset of a physical `LoROM` address (banks `$00-$1F`) in Mesen's `SnesPrgRom` memory.
fn prg_offset(address: u32) -> u32 {
    (address >> 16) * 0x8000 + ((address & 0xFFFF) - 0x8000)
}

/// `start` alone for one byte, `start-end` for a range.
fn range(start: u32, size: u32) -> String {
    if size <= 1 { format!("{start:X}") } else { format!("{start:X}-{:X}", start + size - 1) }
}

/// The `.mlb` text: routines, tables, sync points (`SnesPrgRom`), then variables (`SnesWorkRam`;
/// the ones in the cartridge's SRAM, banks `$70-$7D`, are `SnesSaveRam`), each in file order.
#[must_use]
pub fn mlb(symbols: &Symbols) -> String {
    let mut out = String::new();
    for r in symbols.routines() {
        let _ = writeln!(out, "SnesPrgRom:{:X}:{}", prg_offset(r.address), r.name);
    }
    for t in symbols.tables() {
        let _ = writeln!(out, "SnesPrgRom:{}:{}", range(prg_offset(t.address), t.size), t.name);
    }
    for p in symbols.sync_points() {
        let _ = writeln!(out, "SnesPrgRom:{:X}:{}", prg_offset(p.address), p.name);
    }
    for v in symbols.variables() {
        if (0x70_0000..0x7E_0000).contains(&v.address) {
            let _ =
                writeln!(out, "SnesSaveRam:{}:{}", range(v.address - 0x70_0000, v.size), v.name);
        } else {
            let _ =
                writeln!(out, "SnesWorkRam:{}:{}", range(v.address - 0x7E_0000, v.size), v.name);
        }
    }
    out
}

/// The Lua file the tracer loads: `return { ["name"] = address, ... }` with the physical address
/// of code and tables and the bus address of variables. Names are quoted so a Lua keyword cannot
/// break the file.
#[must_use]
pub fn lua(symbols: &Symbols) -> String {
    let mut out = String::from("-- Generated by `xtask export-mlb`; do not edit.\nreturn {\n");
    let all = symbols
        .routines()
        .iter()
        .map(|r| (&r.name, r.address))
        .chain(symbols.tables().iter().map(|t| (&t.name, t.address)))
        .chain(symbols.sync_points().iter().map(|p| (&p.name, p.address)))
        .chain(symbols.variables().iter().map(|v| (&v.name, v.address)));
    for (name, address) in all {
        let _ = writeln!(out, "  [\"{name}\"] = 0x{address:06X},");
    }
    out.push_str("}\n");
    out
}

/// Writes `dbz.mlb` and `symbols.lua` into `dir`, creating it.
///
/// # Errors
///
/// A directory or file that cannot be written.
pub fn export(symbols: &Symbols, dir: &Path) -> anyhow::Result<[PathBuf; 2]> {
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    let files = [(dir.join("dbz.mlb"), mlb(symbols)), (dir.join("symbols.lua"), lua(symbols))];
    for (path, text) in &files {
        std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(files.map(|(path, _)| path))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SYNTHETIC: &str = r#"
[[routine]]
name = "first_bank"
address = 0x008123
returns = "rts"
timing = "pure"
mode = "original"

[[routine]]
name = "bank_one"
address = 0x018000
returns = "rtl"
timing = "pure"
mode = "original"

[[routine]]
name = "last_bank"
address = 0x1FFFFF
returns = "rtl"
timing = "pure"
mode = "original"

[[table]]
name = "some_table"
address = 0x028000
size = 16

[[sync_point]]
name = "idle"
address = 0x0080CE

[[variable]]
name = "flag"
address = 0x7E0364

[[variable]]
name = "record"
address = 0x7E1400
size = 64

[[variable]]
name = "slot"
address = 0x700100
size = 16
"#;

    fn symbols() -> Symbols {
        Symbols::parse(SYNTHETIC, Path::new("synthetic.toml")).unwrap()
    }

    #[test]
    fn mlb_lines_are_exact() {
        assert_eq!(
            mlb(&symbols()),
            "SnesPrgRom:123:first_bank\n\
             SnesPrgRom:8000:bank_one\n\
             SnesPrgRom:FFFFF:last_bank\n\
             SnesPrgRom:10000-1000F:some_table\n\
             SnesPrgRom:CE:idle\n\
             SnesWorkRam:364:flag\n\
             SnesWorkRam:1400-143F:record\n\
             SnesSaveRam:100-10F:slot\n"
        );
    }

    #[test]
    fn lua_table_lists_every_symbol() {
        assert_eq!(
            lua(&symbols()),
            "-- Generated by `xtask export-mlb`; do not edit.\nreturn {\n\
             \x20 [\"first_bank\"] = 0x008123,\n\
             \x20 [\"bank_one\"] = 0x018000,\n\
             \x20 [\"last_bank\"] = 0x1FFFFF,\n\
             \x20 [\"some_table\"] = 0x028000,\n\
             \x20 [\"idle\"] = 0x0080CE,\n\
             \x20 [\"flag\"] = 0x7E0364,\n\
             \x20 [\"record\"] = 0x7E1400,\n\
             \x20 [\"slot\"] = 0x700100,\n\
             }\n"
        );
    }

    #[test]
    fn export_writes_both_files() {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("nested");
        let [mlb_path, lua_path] = export(&symbols(), &out).unwrap();
        assert_eq!(std::fs::read_to_string(mlb_path).unwrap(), mlb(&symbols()));
        assert_eq!(std::fs::read_to_string(lua_path).unwrap(), lua(&symbols()));
    }
}
