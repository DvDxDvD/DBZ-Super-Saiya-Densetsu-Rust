//! Generates `$OUT_DIR/data.rs` (included by `src/data.rs`) from `re/symbols.toml`: for every
//! `[[variable]]` and `[[table]]` named `some_name`, the constants `SOME_NAME` (the 24-bit
//! address of its first byte) and `SOME_NAME_SIZE` (its size in bytes), and `ALL` listing them.
//!
//! This reads only what it needs with its own small structs. The complete checks (address
//! ranges, overlaps, unique names) belong to `ssd_oracle::Symbols`, which is not a build
//! dependency: the unit tests of `data.rs` load the same file with it and compare.

use serde::Deserialize;
use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

/// Path of the symbols file from the crate root, for cargo's change tracking.
const SYMBOLS: &str = "../../re/symbols.toml";

#[derive(Deserialize)]
struct RawFile {
    #[serde(default)]
    variable: Vec<RawVariable>,
    #[serde(default)]
    table: Vec<RawTable>,
}

#[derive(Deserialize)]
struct RawVariable {
    name: String,
    address: u32,
    /// Default 1.
    size: Option<u32>,
}

#[derive(Deserialize)]
struct RawTable {
    name: String,
    address: u32,
    size: u32,
}

/// One generated entry: what it is, its name, address and size.
struct Entry {
    kind: &'static str,
    name: String,
    address: u32,
    size: u32,
}

fn main() {
    println!("cargo:rerun-if-changed={SYMBOLS}");
    println!("cargo:rerun-if-changed=build.rs");

    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let path = root.join(SYMBOLS);
    let source = fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", path.display()));
    let raw: RawFile =
        toml::from_str(&source).unwrap_or_else(|error| panic!("{}: {error}", path.display()));

    let entries: Vec<Entry> = raw
        .variable
        .into_iter()
        .map(|v| Entry {
            kind: "Variable",
            name: v.name,
            address: v.address,
            size: v.size.unwrap_or(1),
        })
        .chain(raw.table.into_iter().map(|t| Entry {
            kind: "Table",
            name: t.name,
            address: t.address,
            size: t.size,
        }))
        .collect();

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("data.rs");
    fs::write(&out, generate(&entries))
        .unwrap_or_else(|error| panic!("cannot write {}: {error}", out.display()));
}

/// The source of the constants. Panics, naming the entry, on a name that would not make valid
/// and distinct constants.
fn generate(entries: &[Entry]) -> String {
    // `ALL` is generated below: no entry may take its name.
    let mut constants = HashSet::from(["ALL".to_owned()]);
    let mut out = String::from("// Generated by build.rs from re/symbols.toml. Do not edit.\n\n");
    for Entry { kind, name, address, size } in entries {
        let upper = name.to_ascii_uppercase();
        assert!(is_identifier(name), "{SYMBOLS}: name `{name}` is not an identifier");
        for constant in [upper.clone(), format!("{upper}_SIZE")] {
            assert!(
                constants.insert(constant.clone()),
                "{SYMBOLS}: `{name}` generates `{constant}`, already used by another entry or ALL"
            );
        }
        assert!(*address <= 0xFF_FFFF, "{SYMBOLS}: `{name}`: ${address:X} is not a 24-bit address");
        writeln!(
            out,
            "/// {kind} `{name}`: the 24-bit bus address of its first byte.\n\
             pub const {upper}: u32 = 0x{:02X}_{:04X};\n\
             /// Size of `{name}` in bytes.\n\
             pub const {upper}_SIZE: u32 = {size};\n",
            address >> 16,
            address & 0xFFFF
        )
        .unwrap();
    }

    writeln!(
        out,
        "/// Every variable, then every table, of `re/symbols.toml` as `(name, address, size)`, in \
         file order.\n\
         pub const ALL: [(&str, u32, u32); {}] = [",
        entries.len()
    )
    .unwrap();
    for entry in entries {
        let upper = entry.name.to_ascii_uppercase();
        writeln!(out, "    (\"{}\", {upper}, {upper}_SIZE),", entry.name).unwrap();
    }
    out.push_str("];\n");
    out
}

/// Whether `name` matches `[a-z_][a-z0-9_]*` like `ssd_oracle::Symbols` requires, and is not
/// the lone `_`, which is no constant name.
fn is_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    name != "_"
        && chars.next().is_some_and(|first| first.is_ascii_lowercase() || first == '_')
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}
